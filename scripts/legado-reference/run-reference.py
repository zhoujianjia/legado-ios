#!/usr/bin/env python3
"""Stage and execute one added test against the unchanged original Android code.

Only the test, its fixture, external minimum-SDK init script and debug telemetry
settings are overlaid. The source snapshot and generated Google configuration
are prepared by prepare-reference.py.
An Android result is not itself an iOS compatibility result.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import shlex
import signal
import subprocess
import sys
import uuid


REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / ".build/legado-reference/source"
OUTPUT = REPO / ".build/ci-logs/android-reference"
SNAPSHOT = REPO / "Packages/LegadoRuntime/vendor/android-reference"
FIXTURE = REPO / "Packages/LegadoRuntime/jvm/src/test/resources/fixtures/main-source.js"
HARNESS = REPO / "tools/legado-reference/androidTest/LegadoGoldenTraceTest.kt"
INIT_SCRIPT = REPO / "tools/legado-reference/reference.init.gradle"
STAGED_INIT_SCRIPT = SOURCE / "reference.init.gradle"
REFERENCE_MIN_SDK = 26
PACKAGE = "com.legado.app.debug"
TEST_CLASS = "io.legado.app.reference.LegadoGoldenTraceTest"
REMOTE_REPORT = "files/legado-reference/android-golden.json"
HARNESS_RELATIVE = "app/src/androidTest/java/io/legado/app/reference/LegadoGoldenTraceTest.kt"
FIXTURE_RELATIVE = "app/src/androidTest/assets/legado-reference/main-source.js"
GOLDEN_FILENAME = "android-golden.json"
OBSERVED_FILENAME = "android-report-observed.json"
TEST_CONFIGURATION_OVERRIDES = {}


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes((json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode("utf-8"))


def verify_original_files() -> dict:
    manifest = json.loads((SNAPSHOT / "manifest.json").read_bytes())
    for entry in manifest["files"]:
        original_path = SOURCE / entry["path"]
        path = original_path.resolve()
        if not path.is_relative_to(SOURCE.resolve()) or original_path.is_symlink():
            raise ValueError("Unsafe original-source path")
        if path.stat().st_size != entry["bytes"] or digest(path) != entry["sha256"]:
            raise ValueError(f"Original source changed: {entry['path']}")
    return manifest


def stage() -> None:
    manifest = verify_original_files()
    additions = {
        SOURCE / HARNESS_RELATIVE: HARNESS.read_bytes(),
        SOURCE / FIXTURE_RELATIVE: FIXTURE.read_bytes(),
        STAGED_INIT_SCRIPT: INIT_SCRIPT.read_bytes(),
        # Test-only collection settings. All original business files stay intact.
        SOURCE / "app/src/debug/AndroidManifest.xml": b'''<manifest xmlns:android="http://schemas.android.com/apk/res/android">
  <application>
    <meta-data android:name="firebase_analytics_collection_enabled" android:value="false" />
    <meta-data android:name="firebase_performance_collection_enabled" android:value="false" />
    <meta-data android:name="firebase_performance_collection_deactivated" android:value="true" />
    <meta-data android:name="firebase_messaging_auto_init_enabled" android:value="false" />
  </application>
</manifest>
''',
    }
    # Never overwrite a retained source or an unreviewed overlay on a repeated run.
    if any(path.exists() for path in additions):
        raise ValueError("A reference overlay already exists; stage into a fresh source directory")
    for path, contents in additions.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(contents)
    source_commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO, text=True).strip()
    record = {
        "schemaVersion": 1,
        "sourceCommit": source_commit,
        "originalArchiveSHA256": manifest["originalArchiveSHA256"],
        "snapshotSHA256": manifest["snapshotSHA256"],
        "snapshotManifestSHA256": digest(SNAPSHOT / "manifest.json"),
        "fixtureSHA256": digest(FIXTURE),
        "harnessSHA256": digest(HARNESS),
        "initScriptSHA256": digest(INIT_SCRIPT),
        "buildMinSdkVersion": REFERENCE_MIN_SDK,
        "originalFilesVerified": len(manifest["files"]),
        "overlays": [{"path": path.relative_to(SOURCE).as_posix(), "sha256": digest(path)} for path in additions],
        "testConfiguration": {
            "googleServices": "synthetic configuration generated by prepare-reference.py; no upstream credentials",
            "telemetry": "debug manifest disables Firebase analytics/performance collection and messaging auto-init",
            "cronet": "test selects original OkHttp path using the original preference API",
            "network": "original network security config; fixture server listens on emulator loopback only",
            "application": "original Application and AndroidJUnitRunner; no replacement host or business source",
            "minimumSdk": "external reference.init.gradle applies androidComponents.finalizeDsl to :app only; minSdk 23 -> 26 for bundled Rhino MethodHandle bytecode; original Gradle files unchanged",
            **TEST_CONFIGURATION_OVERRIDES,
        },
        "iosValidationPassed": False,
    }
    verify_original_files()
    write_json(OUTPUT / "reference-inputs.json", record)
    print(json.dumps(record, ensure_ascii=True))


def adb_prefix() -> list[str]:
    port = os.environ.get("EMULATOR_PORT")
    if port:
        if not port.isdecimal():
            raise ValueError("Invalid emulator port")
        return ["adb", "-s", "emulator-" + port]
    devices = subprocess.check_output(["adb", "devices"], text=True)
    ready = [line.split()[0] for line in devices.splitlines()[1:]
             if len(line.split()) == 2 and line.split()[1] == "device"]
    if len(ready) != 1 or not ready[0].startswith("emulator-"):
        raise ValueError("Expected exactly one ready emulator; never select a physical Android device")
    return ["adb", "-s", ready[0]]


def run_logged(command: list[str], path: Path, timeout: int) -> int:
    if os.name != "posix":
        raise RuntimeError("Android execution is performed on the Linux CI runner")
    path.parent.mkdir(parents=True, exist_ok=True)
    # shlex.join/quote protect each argument. All subprocess output is streamed
    # while tee retains the same bytes for a failed build or instrumentation run.
    pipeline = shlex.join(command) + " 2>&1 | tee " + shlex.quote(str(path))
    process = subprocess.Popen(["bash", "-o", "pipefail", "-c", pipeline], cwd=REPO, start_new_session=True)
    try:
        return process.wait(timeout=timeout)
    except subprocess.TimeoutExpired:
        os.killpg(process.pid, signal.SIGTERM)
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGKILL)
            process.wait()
        raise TimeoutError("Original Android instrumentation exceeded its deadline") from None


def execute() -> None:
    manifest = verify_original_files()
    inputs = json.loads((OUTPUT / "reference-inputs.json").read_bytes())
    if inputs["fixtureSHA256"] != digest(FIXTURE) or inputs["harnessSHA256"] != digest(HARNESS):
        raise ValueError("Reference fixture/harness changed after staging")
    if inputs["initScriptSHA256"] != digest(INIT_SCRIPT) or inputs["buildMinSdkVersion"] != REFERENCE_MIN_SDK:
        raise ValueError("Reference minimum-SDK configuration changed after staging")
    if digest(STAGED_INIT_SCRIPT) != inputs["initScriptSHA256"]:
        raise ValueError("Staged reference minimum-SDK init script changed")
    for overlay in inputs["overlays"]:
        if digest(SOURCE / overlay["path"]) != overlay["sha256"]:
            raise ValueError("Reference overlay changed after staging")
    adb = adb_prefix()
    reference_run_id = str(uuid.uuid4())
    result = {"schemaVersion": 1, "startedAtUTC": datetime.now(timezone.utc).isoformat(),
              "referenceKind": "original-archive-android-instrumentation", "passed": False,
              "referenceRunId": reference_run_id,
              "sourceCommit": inputs["sourceCommit"], "iosValidationPassed": False}
    command = ["bash", str(SOURCE / "gradlew"), "-p", str(SOURCE), "-I", str(STAGED_INIT_SCRIPT), "--no-daemon", "--max-workers=2",
               "-Dorg.gradle.jvmargs=-Xmx4g -Dfile.encoding=UTF-8", ":app:connectedAppDebugAndroidTest",
               "-Pandroid.testInstrumentationRunnerArguments.class=" + TEST_CLASS,
               "-Pandroid.testInstrumentationRunnerArguments.archiveSHA256=" + manifest["originalArchiveSHA256"],
               "-Pandroid.testInstrumentationRunnerArguments.referenceRunId=" + reference_run_id,
               "--stacktrace"]
    try:
        result["instrumentationExitCode"] = run_logged(command, OUTPUT / "instrumentation.log", 1800)
        exported = subprocess.run([*adb, "exec-out", "run-as", PACKAGE, "cat", REMOTE_REPORT],
                                  cwd=REPO, capture_output=True, timeout=30)
        (OUTPUT / "report-export.stderr.log").write_bytes(exported.stderr)
        if exported.returncode:
            raise RuntimeError("Original app did not export the reference report")
        # Preserve observed bytes for diagnostics, but never promote an old
        # report to this execution's golden output merely because inputs match.
        (OUTPUT / OBSERVED_FILENAME).write_bytes(exported.stdout)
        result["reportSHA256"] = hashlib.sha256(exported.stdout).hexdigest()
        report = json.loads(exported.stdout)
        if not isinstance(report, dict) or report.get("referenceRunId") != reference_run_id:
            raise RuntimeError("Original reference report is stale or does not identify this execution")
        (OUTPUT / GOLDEN_FILENAME).write_bytes(exported.stdout)
        if report.get("referenceKind") != result["referenceKind"] or report.get("passed") is not True:
            raise RuntimeError("Original reading-chain reference failed; preserve its partial trace")
        if report.get("fixtureSHA256") != inputs["fixtureSHA256"] or report.get("originalArchiveSHA256") != manifest["originalArchiveSHA256"]:
            raise RuntimeError("Original reference report does not match the staged inputs")
        if report.get("applicationClass") != "io.legado.app.App":
            raise RuntimeError("Reference did not execute the original Application")
        if report.get("applicationMinSdkVersion") != REFERENCE_MIN_SDK:
            raise RuntimeError("Reference APK minimum SDK does not match the staged override")
        verify_original_files()
        if result["instrumentationExitCode"]:
            raise RuntimeError("Instrumentation failed despite a report file")
        result["passed"] = True
    except Exception as error:
        result["failure"] = f"{type(error).__name__}: {error}"
        raise
    finally:
        try:
            logcat = subprocess.run([*adb, "logcat", "-d", "-v", "threadtime"], capture_output=True, timeout=30)
            (OUTPUT / "logcat.log").write_bytes(logcat.stdout)
        except (OSError, subprocess.TimeoutExpired) as error:
            result["logcatCollectionError"] = type(error).__name__
        result["finishedAtUTC"] = datetime.now(timezone.utc).isoformat()
        write_json(OUTPUT / "execution.json", result)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("stage", "execute"))
    args = parser.parse_args()
    if args.command == "stage":
        stage()
    else:
        execute()


if __name__ == "__main__":
    main()
